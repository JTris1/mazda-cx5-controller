"""PlatformIO pre-build step: turns web/admin.html into src/admin_page.gen.h (gzip, as a C array).

The generated header is not committed. It is rewritten only when the page changed, so unchanged builds stay fast.
"""
import gzip
import hashlib
import os

try:
    Import("env")  # noqa: F821 - provided by SCons when run by PlatformIO
    root = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

src = os.path.join(root, "web", "admin.html")
dst = os.path.join(root, "src", "admin_page.gen.h")


def build():
    html = open(src, "rb").read()
    gz = gzip.compress(html, 9, mtime=0)
    digest = hashlib.sha256(gz).hexdigest()
    if os.path.exists(dst) and f"// sha256 {digest}" in open(dst).read(200):
        return
    rows = []
    for i in range(0, len(gz), 16):
        rows.append("  " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 16]) + ",")
    open(dst, "w").write(
        f"// sha256 {digest}\n// Generated by tools/embed_web.py from web/admin.html. Do not edit, do not commit.\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n"
        f"static const size_t ADMIN_PAGE_GZ_LEN = {len(gz)};\n"
        "static const uint8_t ADMIN_PAGE_GZ[] = {\n" + "\n".join(rows) + "\n};\n")
    print(f"embed_web: admin page {len(html)} bytes -> {len(gz)} bytes gzip")


build()
