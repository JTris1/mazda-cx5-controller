#!/usr/bin/env python3
"""Generates the known-good ECDSA P-256 test vector used by the `authtest` console command.

Needs only the openssl command line. Prints C++ constants to paste into src/auth_vector.h.
The private key is thrown away: the vector only proves the firmware's verify path agrees
with an independent implementation (OpenSSL).
"""
import hashlib, subprocess, tempfile, os

def run(args, **kw):
    return subprocess.run(args, check=True, capture_output=True, **kw).stdout

def der_to_raw(sig):
    # DER: 30 len 02 rlen r 02 slen s
    assert sig[0] == 0x30
    i = 2 if sig[1] < 0x80 else 2 + (sig[1] & 0x7F)
    assert sig[i] == 0x02
    rl = sig[i + 1]; r = sig[i + 2:i + 2 + rl]; i += 2 + rl
    assert sig[i] == 0x02
    sl = sig[i + 1]; s = sig[i + 2:i + 2 + sl]
    fix = lambda b: b.lstrip(b"\x00").rjust(32, b"\x00")
    return fix(r) + fix(s)

def new_key(d, name):
    key = os.path.join(d, name + ".pem")   # one file per key, or the second would overwrite the first
    run(["openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout", "-out", key])
    der = run(["openssl", "ec", "-in", key, "-pubout", "-outform", "DER"])
    return key, der[-65:]          # uncompressed point 04 || X || Y

def carr(name, data):
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[{len(data)}] = {{{body}}};"

nonce = "00112233445566778899aabbccddeeff"
key_id = "test"
method = "POST"
path = "/api/v1/heater"
body = b'{"seat":"driver","level":"high"}'
signed = f"CX5-V1\n{nonce}\n{key_id}\n{method}\n{path}\n{hashlib.sha256(body).hexdigest()}".encode()

with tempfile.TemporaryDirectory() as d:
    key, pub = new_key(d, "signer")
    _, other_pub = new_key(d, "other")
    msg = os.path.join(d, "m.bin")
    open(msg, "wb").write(signed)
    sig = der_to_raw(run(["openssl", "dgst", "-sha256", "-sign", key, msg]))

print("// Generated by tools/gen_auth_vector.py. Do not edit by hand.")
print("#pragma once\n#include <stdint.h>\n")
print(f'static const char VEC_NONCE[] = "{nonce}";')
print(f'static const char VEC_KEY_ID[] = "{key_id}";')
print(f'static const char VEC_METHOD[] = "{method}";')
print(f'static const char VEC_PATH[] = "{path}";')
print(f'static const char VEC_BODY[] = R"({body.decode()})";')
print(carr("VEC_PUB", pub))
print(carr("VEC_OTHER_PUB", other_pub))
print(carr("VEC_SIG", sig))
