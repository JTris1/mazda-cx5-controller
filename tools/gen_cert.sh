#!/bin/sh
# Generates the device's self-signed TLS certificate and writes src/tls_cert.h.
#
# Usage: tools/gen_cert.sh [tunnel-ip]        (default 192.168.10.2, the ESP32's WireGuard address)
#
# The certificate is valid for 10 years and names the tunnel IP, so clients can connect to
# https://<tunnel-ip>/. Clients do not trust it through a CA: they pin the SHA-256 fingerprint
# printed at the end (compare it on first use, then keep it). src/tls_cert.h contains the
# private key and is listed in .gitignore: never commit it.
set -e
IP="${1:-192.168.10.2}"
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="$HERE/../src/tls_cert.h"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

openssl ecparam -name prime256v1 -genkey -noout -out "$TMP/key.pem"
openssl req -new -x509 -key "$TMP/key.pem" -sha256 -days 3650 \
  -subj "/CN=cx5-controller" -addext "subjectAltName=IP:$IP" -out "$TMP/cert.pem"
openssl x509 -in "$TMP/cert.pem" -outform DER -out "$TMP/cert.der"
openssl ec -in "$TMP/key.pem" -outform DER -out "$TMP/key.der" 2>/dev/null
FP="$(openssl x509 -in "$TMP/cert.pem" -noout -fingerprint -sha256 | cut -d= -f2)"

python3 - "$TMP/cert.der" "$TMP/key.der" "$FP" "$IP" > "$OUT" <<'PY'
import sys
cert, key = open(sys.argv[1], "rb").read(), open(sys.argv[2], "rb").read()
def arr(name, b):
    body = ", ".join(f"0x{x:02x}" for x in b)
    return f"static unsigned char {name}[{len(b)}] = {{{body}}};"
print("// Generated by tools/gen_cert.sh. Contains the private key: never commit this file.")
print("#pragma once\n")
print(f'static const char TLS_CERT_FINGERPRINT[] = "{sys.argv[3]}";   // SHA-256 of the certificate')
print(f'static const char TLS_CERT_IP[] = "{sys.argv[4]}";')
print(arr("TLS_CERT_DER", cert))
print(arr("TLS_KEY_DER", key))
PY
echo "Wrote $OUT"
echo "Certificate SHA-256 fingerprint (pin this in clients):"
echo "$FP"
